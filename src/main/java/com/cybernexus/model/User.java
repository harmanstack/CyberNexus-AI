package com.cybernexus.model;

import java.time.LocalDateTime;

/**
 * User represents a user account in the CyberNexus AI system.
 * Maps to the 'users' table in MySQL database.
 * Part of Harman's Backend Responsibilities.
 *
 * Implements strict OOP Encapsulation:
 * - All instance variables are private.
 * - Access is provided through public getters and setters.
 * - Passwords are never stored in plain text (only BCrypt hash).
 */
public class User {

    private int id;
    private String name;
    private String email;
    private String passwordHash;
    private String role;
    private LocalDateTime createdAt;

    /**
     * Default No-Argument Constructor.
     * Required for JavaBean standard and serialization.
     */
    public User() {
    }

    /**
     * Constructor for creating a new User before inserting into MySQL
     * (id and createdAt will be auto-generated by MySQL).
     */
    public User(String name, String email, String passwordHash, String role) {
        this.name = name;
        this.email = email;
        this.passwordHash = passwordHash;
        this.role = role == null ? "user" : role;
    }

    /**
     * Full Constructor for populating User entity retrieved from MySQL ResultSet.
     */
    public User(int id, String name, String email, String passwordHash,
                String role, LocalDateTime createdAt) {
        this.id = id;
        this.name = name;
        this.email = email;
        this.passwordHash = passwordHash;
        this.role = role;
        this.createdAt = createdAt;
    }

    // --- Getters and Setters (Encapsulation) ---

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    // Alias for Evaluation spec compatibility
    public int getUserId() {
        return id;
    }

    public void setUserId(int userId) {
        this.id = userId;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    // Alias for Evaluation spec compatibility
    public String getUsername() {
        return name;
    }

    public void setUsername(String username) {
        this.name = username;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPasswordHash() {
        return passwordHash;
    }

    public void setPasswordHash(String passwordHash) {
        this.passwordHash = passwordHash;
    }

    public String getRole() {
        return role;
    }

    public void setRole(String role) {
        this.role = role;
    }

    /**
     * Helper method to verify if the user possesses administrator privileges.
     *
     * @return true if role is "admin" (case-insensitive)
     */
    public boolean isAdmin() {
        return "admin".equalsIgnoreCase(role);
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }

    /**
     * Secure toString representation.
     * Note: Masking password hash to prevent accidental leakage in console logs.
     */
    @Override
    public String toString() {
        return "User{" +
                "id=" + id +
                ", name='" + name + '\'' +
                ", email='" + email + '\'' +
                ", role='" + role + '\'' +
                ", passwordHash='[PROTECTED]'" +
                ", createdAt=" + createdAt +
                '}';
    }

    /**
     * Standalone main method to test User encapsulation and getters/setters.
     */
    public static void main(String[] args) {
        System.out.println("=== Testing User Model Class (Harman) ===");
        User user = new User(1, "Harman", "harman@cybernexus.com", "$2a$10$hashedPasswordExample", "admin", LocalDateTime.now());

        System.out.println("User ID: " + user.getUserId());
        System.out.println("Username: " + user.getUsername());
        System.out.println("Email: " + user.getEmail());
        System.out.println("Is Admin: " + user.isAdmin());
        System.out.println("Protected toString(): " + user);
        System.out.println("[SUCCESS] User model encapsulation verified!");
    }
}
