package com.cybernexus.detection;

import com.cybernexus.model.ScanResult;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * RiskAnalyzer calculates weighted threat scores and determines risk levels.
 * Part of Tanisha's Assigned Responsibilities (Cybersecurity Detection Engine).
 *
 * Scoring Rules:
 * 1. Accumulates numerical weights for each detected indicator.
 * 2. Clamps score strictly between 0 and 100 to satisfy MySQL database constraints.
 * 3. Categorizes risk levels strictly according to specification:
 *    - LOW:    0 to 30
 *    - MEDIUM: 31 to 60
 *    - HIGH:   61 to 100
 * 4. Packages final findings into an immutable ScanResult model.
 */
public class RiskAnalyzer {

    // Weight lookup table mapping threat indicator categories to severity points
    private final Map<String, Integer> keywordWeights = new HashMap<>();

    public RiskAnalyzer() {
        // High-severity deception & credential harvesting
        keywordWeights.put("impersonation", 35);
        keywordWeights.put("sensitive credentials", 30);
        keywordWeights.put("sensitive information", 30);
        keywordWeights.put("@", 30);
        keywordWeights.put("financial or payment", 25);
        keywordWeights.put("ip address", 25);
        keywordWeights.put("shortener", 25);

        // Medium-severity triggers & indicators
        keywordWeights.put("top-level domain", 20);
        keywordWeights.put("action keyword", 20);
        keywordWeights.put("sensitive keyword", 20);
        keywordWeights.put("prize", 20);
        keywordWeights.put("lottery", 20);
        keywordWeights.put("http instead", 15);
        keywordWeights.put("urgency", 15);
        keywordWeights.put("open a link", 15);

        // Secondary / context indicators
        keywordWeights.put("embedded web link", 10);
        keywordWeights.put("hyphens", 10);
        keywordWeights.put("generic greeting", 10);
        keywordWeights.put("unusually long", 10);
        keywordWeights.put("empty", 5);
    }

    /**
     * Evaluates a list of threat reasons and builds a completed ScanResult object.
     *
     * @param scanType the kind of scan performed ("URL" or "MESSAGE")
     * @param input    the raw text or URL scanned
     * @param reasons  the findings generated by URLDetector or MessageDetector
     * @return a completed ScanResult containing normalized score, level, and reasons
     */
    public ScanResult analyze(String scanType, String input, List<String> reasons) {
        if (reasons == null || reasons.isEmpty()) {
            return new ScanResult(scanType, input, 0, "LOW", new ArrayList<>());
        }

        int rawScore = 0;
        for (String reason : reasons) {
            rawScore += weightFor(reason);
        }

        int finalScore = clamp(rawScore);
        String level = levelForScore(finalScore);

        return new ScanResult(scanType, input, finalScore, level, reasons);
    }

    /**
     * Maps a numerical risk score (0-100) to its standardized risk level category.
     *
     * @param score the calculated risk score
     * @return "LOW", "MEDIUM", or "HIGH"
     */
    public String levelForScore(int score) {
        if (score <= 30) {
            return "LOW";
        }
        if (score <= 60) {
            return "MEDIUM";
        }
        return "HIGH";
    }

    /**
     * Ensures score strictly adheres to the 0 <= score <= 100 boundary.
     * Prevents violating MySQL database check constraint.
     */
    public int clamp(int score) {
        return Math.max(0, Math.min(100, score));
    }

    /**
     * Finds the matching numerical weight for a specific reason string.
     */
    public int weightFor(String reason) {
        if (reason == null) {
            return 0;
        }
        String lowered = reason.toLowerCase(Locale.ROOT);
        for (Map.Entry<String, Integer> entry : keywordWeights.entrySet()) {
            if (lowered.contains(entry.getKey())) {
                return entry.getValue();
            }
        }
        // Default baseline weight for unmatched findings
        return 10;
    }

    /**
     * Standalone main method to demonstrate risk scoring and classification.
     * Right-click inside this file and select: Run 'RiskAnalyzer.main()'
     */
    public static void main(String[] args) {
        System.out.println("=== Testing RiskAnalyzer (Tanisha - Cybersecurity Engine) ===\n");

        RiskAnalyzer analyzer = new RiskAnalyzer();

        // 1. Scenario LOW Risk (Clean URL)
        List<String> lowReasons = List.of();
        ScanResult lowResult = analyzer.analyze("URL", "https://google.com", lowReasons);
        printResult("Scenario 1: Clean Legit Site", lowResult);

        // 2. Scenario MEDIUM Risk (Insecure HTTP + Abused TLD)
        List<String> mediumReasons = List.of(
                "Uses unencrypted HTTP instead of HTTPS",
                "Uses a frequently abused top-level domain: .xyz"
        );
        ScanResult mediumResult = analyzer.analyze("URL", "http://my-blog.xyz", mediumReasons);
        printResult("Scenario 2: Insecure Suspicious Link", mediumResult);

        // 3. Scenario HIGH Risk (Urgent Credential Phishing with Shortener)
        List<String> highReasons = List.of(
                "Uses artificial urgency language: 'within 24 hours'",
                "Asks for sensitive credentials/information: 'password'",
                "URL shortener hides the final destination (bit.ly)",
                "Pushes the reader to open a link: 'click here'"
        );
        ScanResult highResult = analyzer.analyze("MESSAGE", "Click here bit.ly/123 to verify password", highReasons);
        printResult("Scenario 3: Severe Phishing Scam", highResult);
    }

    private static void printResult(String title, ScanResult result) {
        System.out.println("--- " + title + " ---");
        System.out.println("Scan Type:   " + result.getScanType());
        System.out.println("Risk Score:  " + result.getRiskScore() + " / 100");
        System.out.println("Risk Level:  " + result.getRiskLevel());
        System.out.println("Findings:    " + result.joinedReasons());
        System.out.println();
    }
}
